def load_json_if_exists(path: Path) -> dict[str, Any]:
    if not path.exists():
        return {}
    return json.loads(path.read_text(encoding="utf-8"))


def requirement_rows() -> list[dict[str, Any]]:
    readiness_by_id = {row["req_id"]: row for row in readiness_audit()}
    rows: list[dict[str, Any]] = []
    for requirement in REQUIREMENTS:
        checks = [evaluate_completion_check(check) for check in requirement.checks]
        evidence_ok = all(check["ok"] for check in checks)
        status = STATUS_BY_REQ.get(requirement.req_id)
        if status is None:
            production_level = "sidecar_complete"
            production_complete = True
            notes = ("Implemented and validated in improve_workspace; no production-pending item is registered for this requirement.",)
            blockers: tuple[str, ...] = ()
        else:
            production_level = status.production_level
            production_complete = status.production_complete
            notes = status.notes
            blockers = status.blockers
        readiness = readiness_by_id.get(requirement.req_id)
        rows.append({
            "req_id": requirement.req_id,
            "section": requirement.section,
            "title": requirement.title,
            "sidecar_evidence_ok": evidence_ok,
            "production_pending": requirement.production_pending,
            "production_level": production_level,
            "production_complete": production_complete,
            "source_anchors_ok": None if readiness is None else bool(readiness["anchors_ok"]),
            "notes": list(notes),
            "blockers": list(blockers),
        })
    return rows


def build_payload() -> dict[str, Any]:
    rows = requirement_rows()
    production_relevant = [row for row in rows if row["production_pending"]]
    full_complete = [row for row in production_relevant if row["production_complete"]]
    by_level: dict[str, int] = {}
    for row in rows:
        by_level[row["production_level"]] = by_level.get(row["production_level"], 0) + 1
    bridge = load_json_if_exists(REPO_ROOT / "improve_workspace/production_experiment_bridge_executed.json")
    production_ablation = load_json_if_exists(REPO_ROOT / "improve_workspace/production_clect_ablation.json")
    performance = load_json_if_exists(REPO_ROOT / "improve_workspace/performance_change_summary.json")
    summary = {
        "total_requirements": len(rows),
        "sidecar_evidence_ok_count": sum(1 for row in rows if row["sidecar_evidence_ok"]),
        "production_relevant_count": len(production_relevant),
        "production_source_anchor_ok_count": sum(1 for row in production_relevant if row["source_anchors_ok"]),
        "production_full_complete_count": len(full_complete),
        "production_remaining_count": len(production_relevant) - len(full_complete),
        "production_completion_complete": len(production_relevant) == len(full_complete),
        "levels": by_level,
        "executed_smoke_ok": bool(bridge.get("ok", False)),
        "production_clect_integrated": bool(
            production_ablation.get("ok", False) and
            production_ablation.get("production_clect_integrated", False)
        ),
        "production_clect_ablation_ok": bool(production_ablation.get("ok", False)),
        "performance_summary_available": bool(performance),
    }
    return {
        "summary": summary,
        "requirements": rows,
    }


def write_md(path: Path, payload: dict[str, Any]) -> None:
    summary = payload["summary"]
    lines = [
        "# Production Completion Status",
        "",
        "This audit classifies the current `docs/improve.md` implementation by completion level.",
        "It is stricter than source-anchor readiness and does not treat scaffolds or proposals as full production integration.",
        "",
        f"- total requirements: `{summary['total_requirements']}`",
        f"- sidecar evidence ok: `{summary['sidecar_evidence_ok_count']}`",
        f"- production-relevant items: `{summary['production_relevant_count']}`",
        f"- production source anchors ok: `{summary['production_source_anchor_ok_count']}`",
        f"- full production complete items: `{summary['production_full_complete_count']}`",
        f"- production remaining items: `{summary['production_remaining_count']}`",
        f"- production completion complete: `{summary['production_completion_complete']}`",
        f"- executed-smoke bridge ok: `{summary['executed_smoke_ok']}`",
        f"- production C-LECT integrated: `{summary['production_clect_integrated']}`",
        "",
        "## Level Counts",
        "",
        "| Level | Count |",
        "| --- | ---: |",
    ]
    for level, count in sorted(summary["levels"].items()):
        lines.append(f"| `{level}` | {count} |")
    lines.extend([
        "",
        "## Requirement Status",
        "",
        "| Req | Sidecar | Production level | Full prod. | Source anchors | Title |",
        "| --- | ---: | --- | ---: | ---: | --- |",
    ])
    for row in payload["requirements"]:
        anchors = "" if row["source_anchors_ok"] is None else str(row["source_anchors_ok"])
        lines.append(
            f"| `{row['req_id']}` | {row['sidecar_evidence_ok']} | "
            f"`{row['production_level']}` | {row['production_complete']} | "
            f"{anchors} | {row['title']} |"
        )
    lines.append("")
    lines.append("## Remaining Production Work")
    for row in payload["requirements"]:
        if row["production_complete"]:
            continue
        lines.append("")
        lines.append(f"### {row['req_id']} {row['title']}")
        for note in row["notes"]:
            lines.append(f"- {note}")
        for blocker in row["blockers"]:
            lines.append(f"- Remaining: {blocker}")
    path.write_text("\n".join(lines) + "\n", encoding="utf-8")


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--json-out", default="improve_workspace/production_completion_status.json")
    parser.add_argument("--md-out", default="improve_workspace/production_completion_status.md")
    args = parser.parse_args()

    payload = build_payload()
    json_path = REPO_ROOT / args.json_out
    md_path = REPO_ROOT / args.md_out
    json_path.write_text(json.dumps(payload, indent=2, ensure_ascii=False), encoding="utf-8")
    write_md(md_path, payload)
    print(json.dumps({
        "json_out": str(json_path),
        "md_out": str(md_path),
        **payload["summary"],
    }, indent=2, ensure_ascii=False))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
