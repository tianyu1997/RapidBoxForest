"""Classify improve.md implementation status by production-completion level.

The requirement audit proves sidecar evidence exists.  The production readiness
audit proves production source anchors exist.  This audit is stricter: it
separates sidecar completion, partial production scaffolds, proposal-only work,
and executed-smoke validation so the current state is not mistaken for full
production integration.
"""

